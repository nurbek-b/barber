"""Uploaded media (barber photos): local disk or a Cloud Storage bucket.

Public URLs are always ``<media_url_prefix>/<key>`` (``/media/barbers/x.jpg``):
* local  - Nginx (prod) or StaticFiles (dev) serves the directory;
* gcs    - the API streams the object (Firebase Hosting rewrites /media/** to Cloud Run and
           its CDN caches the immutable response), so the bucket stays private.
"""

from __future__ import annotations

import asyncio
import contextlib
import re
from functools import lru_cache
from pathlib import Path
from typing import Any, Protocol

from app.core.config import Settings

# keys are generated by us: "<folder>/<uuid>-<hex>.<ext>"
KEY_RE = re.compile(r"^[a-z]+/[A-Za-z0-9-]+\.(jpg|png|webp)$")
CONTENT_TYPES = {"jpg": "image/jpeg", "png": "image/png", "webp": "image/webp"}


class MediaStorage(Protocol):
    async def save(self, key: str, content: bytes) -> None: ...
    async def delete(self, key: str) -> None: ...
    async def load(self, key: str) -> bytes | None: ...


def content_type(key: str) -> str:
    return CONTENT_TYPES.get(key.rsplit(".", 1)[-1], "application/octet-stream")


class LocalMediaStorage:
    def __init__(self, root: str) -> None:
        self.root = Path(root)

    def _path(self, key: str) -> Path | None:
        if not KEY_RE.match(key):
            return None
        root = self.root.resolve()
        path = (root / key).resolve()
        return path if root in path.parents else None

    async def save(self, key: str, content: bytes) -> None:
        path = self._path(key)
        if path is None:
            raise ValueError(f"bad media key: {key}")

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)

        await asyncio.to_thread(write)

    async def delete(self, key: str) -> None:
        path = self._path(key)
        if path is not None:
            await asyncio.to_thread(path.unlink, missing_ok=True)

    async def load(self, key: str) -> bytes | None:
        path = self._path(key)
        if path is None or not path.is_file():
            return None
        return await asyncio.to_thread(path.read_bytes)


class GcsMediaStorage:
    def __init__(self, bucket: str) -> None:
        from google.cloud import storage  # imported lazily: not needed for local deploys

        self._bucket: Any = storage.Client().bucket(bucket)

    async def save(self, key: str, content: bytes) -> None:
        if not KEY_RE.match(key):
            raise ValueError(f"bad media key: {key}")
        blob = self._bucket.blob(key)
        blob.cache_control = "public, max-age=31536000, immutable"
        await asyncio.to_thread(blob.upload_from_string, content, content_type=content_type(key))

    async def delete(self, key: str) -> None:
        from google.api_core.exceptions import NotFound

        if not KEY_RE.match(key):
            return
        with contextlib.suppress(NotFound):
            await asyncio.to_thread(self._bucket.blob(key).delete)

    async def load(self, key: str) -> bytes | None:
        from google.api_core.exceptions import NotFound

        if not KEY_RE.match(key):
            return None
        try:
            data: bytes = await asyncio.to_thread(self._bucket.blob(key).download_as_bytes)
        except NotFound:
            return None
        return data


@lru_cache
def _storage(backend: str, location: str) -> MediaStorage:
    if backend == "gcs":
        return GcsMediaStorage(location)
    return LocalMediaStorage(location)


def get_media_storage(settings: Settings) -> MediaStorage:
    if settings.media_backend == "gcs":
        if not settings.media_bucket:
            raise RuntimeError("MEDIA_BUCKET is required when MEDIA_BACKEND=gcs")
        return _storage("gcs", settings.media_bucket)
    return _storage("local", settings.media_dir)


def url_for(settings: Settings, key: str) -> str:
    return f"{settings.media_url_prefix}/{key}"


def key_from_url(settings: Settings, url: str | None) -> str | None:
    prefix = f"{settings.media_url_prefix}/"
    if url and url.startswith(prefix):
        return url.removeprefix(prefix)
    return None
