export const DICTIONARIES: Record<Lang, Dictionary> = { ru, ky, en };

export function normalizeLang(value: string | null | undefined): Lang {
  const short = (value ?? "").split("-")[0]?.toLowerCase();
  return short === "ky" || short === "en" ? short : "ru";
}

export function translate(
  lang: Lang,
  key: MessageKey,
  values?: Record<string, string | number>,
): string {
  const template = DICTIONARIES[lang][key] ?? ru[key];
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

export const LangContext = createContext<Lang>("ru");

export function useLang(): Lang {
  return useContext(LangContext);
}

export function useT() {
  const lang = useLang();
  return useCallback(
    (key: MessageKey, values?: Record<string, string | number>) => translate(lang, key, values),
    [lang],
  );
}

/** Pick a localized catalog name: {ru, ky, en} with ru fallback. */
export function pickI18n(value: Record<string, string> | undefined, lang: Lang): string {
  if (!value) return "";
  return value[lang] || value.ru || Object.values(value)[0] || "";
}
