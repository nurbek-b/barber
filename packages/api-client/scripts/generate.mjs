// Regenerates openapi.json (from the FastAPI app, no DB needed) and src/schema.d.ts.
// `--check` fails when the committed files differ from what the backend produces (CI).
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const backend = resolve(pkg, "../../backend");
const check = process.argv.includes("--check");

const python =
  process.env.BACKEND_PYTHON ??
  [join(backend, ".venv/bin/python"), "python3"].find((p) => p === "python3" || existsSync(p));

const tmp = mkdtempSync(join(tmpdir(), "openapi-"));
const specPath = join(tmp, "openapi.json");
execFileSync(python, ["-m", "app.cli", "export-openapi", specPath], {
  cwd: backend,
  stdio: ["ignore", "ignore", "inherit"],
  env: { ...process.env, ENV: process.env.ENV ?? "dev", LOG_JSON: "false" },
});
const spec = readFileSync(specPath, "utf8");
const header =
  "// Generated by packages/api-client/scripts/generate.mjs from the backend OpenAPI schema.\n" +
  "// Do not edit by hand: run `pnpm gen:api`.\n\n";
const types = header + astToString(await openapiTS(JSON.parse(spec)));

const targets = [
  [join(pkg, "openapi.json"), spec],
  [join(pkg, "src/schema.d.ts"), types],
];

if (check) {
  const stale = targets.filter(
    ([path, content]) => !existsSync(path) || readFileSync(path, "utf8") !== content,
  );
  if (stale.length) {
    console.error(`api-client is out of date: ${stale.map(([p]) => p).join(", ")}`);
    console.error("Run `pnpm gen:api` and commit the result.");
    process.exit(1);
  }
  console.log("api-client is up to date");
} else {
  for (const [path, content] of targets) writeFileSync(path, content);
  console.log("generated openapi.json and src/schema.d.ts");
}
